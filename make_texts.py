OUT_DIR = "texts"


def main() -> int:
    ref_len = len(REFERENCE)
    lo, hi = ref_len * 0.9, ref_len * 1.1
    print(f"Reference: {ref_len} chars, allowed range: {lo:.0f}-{hi:.0f}")

    os.makedirs(OUT_DIR, exist_ok=True)
    ok = True
    for i, text in enumerate(TEXTS, 1):
        n = len(text)
        status = "OK" if lo <= n <= hi else "OUT OF RANGE"
        if status != "OK":
            ok = False
        print(f"variant_{i:03d}.txt: {n} chars ({n / ref_len * 100:.1f}%) {status}")
        with open(os.path.join(OUT_DIR, f"variant_{i:03d}.txt"), "w", encoding="utf-8") as f:
            f.write(text + "\n")

    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
