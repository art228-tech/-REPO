#!/usr/bin/env python3
"""Generate rewritten variants of the reference promo text as .txt files.

Each variant must stay within +-10% of the reference character count,
and its first sentence must stay within +-10% of the reference's first
sentence length.
"""
import os
import re
import sys


def first_sentence(text: str) -> str:
    match = re.match(r".*?[.!?]", text)
    return match.group(0) if match else text

REFERENCE = (
    "Где разработчики оставили нам ультрахаосдроп? Совсем Недавно на своих "
    "каналах суперсэлл оставили нам пасхалку, в которой как они говорят "
    "спрятана награда для всех! Но сколько же хаос ящиков нам дадут и где "
    "найти пасхалку? Я уже все сделал и нашел их, держите!"
)

TEXTS = [
    "Суперсэлл опять запустили охоту за секретами! На своих каналах разработчики спрятали пасхалку и намекнули, что внутри — ультра хаос дропы для всех игроков. Я потратил вечер, но разгадал её! Сколько ультра хаос дропов дадут и где искать — рассказываю прямо сейчас!",
    "Вы не поверите, что устроили нам суперсэлл! Прямо в своих соцсетях они запрятали пасхалку, а внутри неё — хаосдропы для каждого игрока. Никто не мог её разгадать, но я справился и уже забрал свои хаосдропы! Показываю, где лежит секрет и как получить награду!",
    "Бравл пасс за простую пасхалку — это реально? Да! Разработчики недавно оставили на своих каналах хитрую загадку и пообещали, что нашедших ждёт награда. Я проверил всё сам: пасхалка настоящая, и бравл пасс действительно можно забрать! Покажу, где он спрятан!",
    "Суперсэлл тихо спрятали в постах новую пасхалку! Внутри — ультра ящики, награда для тех, кто её отыщет. Я перерыл все каналы разработчиков и наконец-то обнаружил секрет! Сколько ультра ящиков нам достанется и как их забрать — держите полный разбор!",
    "Слышали уже про новую пасхалку от суперсэлл? Разработчики опубликовали её на своих каналах и заявили, что внутри спрятаны хаосдропы для всех желающих. Осталось понять, где искать и сколько хаосдропов дадут. Я всё уже выяснил и готов поделиться — забирайте!",
    "Каждый игрок может получить ультра хаос дропы! Но об этом почти никто не знает: недавно суперсэлл оставили на своих каналах пасхалку с наградой для всех. Я нашёл её первым и рассказываю, сколько ультра хаос дропов дают и где их искать!",
    "Охота за секретом суперсэлл официально началась! Разработчики спрятали на своих каналах пасхалку и намекнули на награду для каждого. Угадайте, что внутри? Ультра ящики! Я прошёл весь квест и знаю, сколько ультра ящиков нам приготовили и где секрет. Показываю!",
    "Такого поворота от суперсэлл никто точно не ждал! На своих каналах они запрятали пасхалку, а наградой сделали бравл пасс! Найти секрет оказалось непросто — я убил на это кучу времени. Зато знаю, где лежит пасхалка и как забрать бравл пасс. Ловите гайд!",
    "Успейте забрать свои хаосдропы, пока не поздно! Суперсэлл устроили квест: на их каналах спрятана пасхалка, и каждый, кто её найдёт, получит награду. Я уже отыскал секрет и забрал свои хаосдропы. Рассказываю, где искать пасхалку и сколько всего нам дадут!",
    "Суперсэлл приготовили ультра хаос дропы для всех? Да, недавно разработчики опубликовали у себя на каналах пасхалку и пообещали награду каждому, кто её разгадает. У меня получилось! Покажу, где искать секрет и сколько ультра хаос дропов дают!",
]

OUT_DIR = "texts"


def main() -> int:
    ref_len = len(REFERENCE)
    ref_fs_len = len(first_sentence(REFERENCE))
    lo, hi = ref_len * 0.9, ref_len * 1.1
    fs_lo, fs_hi = ref_fs_len * 0.9, ref_fs_len * 1.1
    print(f"Reference: {ref_len} chars total, allowed {lo:.0f}-{hi:.0f}; "
          f"first sentence {ref_fs_len} chars, allowed {fs_lo:.0f}-{fs_hi:.0f}")

    os.makedirs(OUT_DIR, exist_ok=True)
    ok = True
    for i, text in enumerate(TEXTS, 1):
        n = len(text)
        fs = len(first_sentence(text))
        total_ok = lo <= n <= hi
        fs_ok = fs_lo <= fs <= fs_hi
        status = "OK" if (total_ok and fs_ok) else "OUT OF RANGE"
        if status != "OK":
            ok = False
        print(f"variant_{i:03d}.txt: total {n} ({n / ref_len * 100:.1f}%), "
              f"first sentence {fs} ({fs / ref_fs_len * 100:.1f}%) {status}")
        with open(os.path.join(OUT_DIR, f"variant_{i:03d}.txt"), "w", encoding="utf-8") as f:
            f.write(text + "\n")

    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
